HELMET_CLASSES = [0, 3]
NO_HELMET_CLASSES = [5, 6]
PERSON_CLASSES = HELMET_CLASSES + NO_HELMET_CLASSES

import cv2
import os

def yolo_to_bbox(w, h, x, y, bw, bh):
    return (
        int((x - bw/2) * w),
        int((y - bh/2) * h),
        int((x + bw/2) * w),
        int((y + bh/2) * h)
    )

def create_cnn_dataset(img_dir, label_dir, out_dir):
    for img_name in os.listdir(img_dir):
        if not img_name.endswith(".jpg"):
            continue

        img_path = os.path.join(img_dir, img_name)
        label_path = os.path.join(label_dir, img_name.replace(".jpg", ".txt"))

        if not os.path.exists(label_path):
            continue

        img = cv2.imread(img_path)
        h, w, _ = img.shape

        with open(label_path) as f:
            for i, line in enumerate(f):
                cls, x, y, bw, bh = map(float, line.split())
                cls = int(cls)

                if cls not in PERSON_CLASSES:
                    continue  # skip bike

                x1, y1, x2, y2 = yolo_to_bbox(w, h, x, y, bw, bh)
                crop = img[y1:y2, x1:x2]

                if crop.size == 0:
                    continue

                label = "helmet" if cls in HELMET_CLASSES else "no_helmet"
                save_dir = os.path.join(out_dir, label)
                os.makedirs(save_dir, exist_ok=True)

                cv2.imwrite(f"{save_dir}/{img_name}_{i}.jpg", crop)

